public enum TokenType {

    // Arithmic - Operators
    PLUS, MINUS, MUL, DIV,

    // Logical - Operators
    EQUALS, GREATER, LOWER,

    // Expressions
    IF, LET, DEF, DEFN, LIST, HEAD, TAIL, NTH, STR, PRINT, DO,

    // Identifiers
    ID, NUMBER, STRING, BOOL,

    // Misc
    LBRACK, RBRACK, EOF

    }